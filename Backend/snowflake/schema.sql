-- Optional analytics warehouse schema. Run in your Snowflake database/schema.
-- Demo rows must be labeled synthetic. Do not load real donor PII without approval and consent.
CREATE TABLE IF NOT EXISTS DONATION (
  DONATION_ID VARCHAR(64) PRIMARY KEY,
  BLOOD_GROUP VARCHAR(3) NOT NULL,
  DONATION_DATE DATE NOT NULL,
  LOCATION VARCHAR(160) NOT NULL,
  UNITS NUMBER(10,0) NOT NULL,
  REGION VARCHAR(80) DEFAULT 'India',
  IS_SYNTHETIC BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS INVENTORY (
  INVENTORY_ID VARCHAR(64) PRIMARY KEY,
  BLOOD_BANK VARCHAR(160) NOT NULL,
  BLOOD_BANK_ID VARCHAR(64),
  BLOOD_GROUP VARCHAR(3) NOT NULL,
  UNITS NUMBER(10,0) NOT NULL,
  SAFETY_FLOOR NUMBER(10,0) NOT NULL,
  EXPECTED_INCOMING_UNITS NUMBER(10,0) DEFAULT 0,
  COLLECTION_DATE DATE,
  EXPIRY_DATE DATE,
  REGION VARCHAR(80) DEFAULT 'India',
  UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  IS_SYNTHETIC BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS REQUEST (
  REQUEST_ID VARCHAR(64) PRIMARY KEY,
  HOSPITAL VARCHAR(160) NOT NULL,
  BLOOD_GROUP VARCHAR(3) NOT NULL,
  UNITS_REQUIRED NUMBER(10,0) NOT NULL,
  URGENCY VARCHAR(20) NOT NULL,
  REQUEST_DATE TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  REGION VARCHAR(80) DEFAULT 'India',
  IS_SYNTHETIC BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS DONOR_NETWORK (
  DONOR_ID VARCHAR(64) PRIMARY KEY,
  BLOOD_GROUP VARCHAR(3) NOT NULL,
  LOCATION_ZONE VARCHAR(160),
  AVAILABLE BOOLEAN DEFAULT FALSE,
  LAST_DONATION DATE,
  CONSENT BOOLEAN DEFAULT FALSE,
  REGION VARCHAR(80) DEFAULT 'India',
  DATASET_LABEL VARCHAR(40) DEFAULT 'SYNTHETIC_DEMO'
  -- Prefer pseudonymous identifiers; keep contact details out of analytics tables.
);
